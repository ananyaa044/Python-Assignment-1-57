#38. Write a program to display the length of a string, list, tuple and dictionary using len().
s = "Hello, World!"
l = [1, 2, 3, 4, 5]
t = (10, 20.5, "Python", True)
d = {
    "Roll No": 57,
    "Name": "Ananya",
    "Marks": 90
}
print("Length of string:", len(s))
print("Length of list:", len(l))   
print("Length of tuple:", len(t))
print("Length of dictionary:", len(d))
